'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const base=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(base,p),'utf8');
const data=JSON.parse(read('content/caminos-ramak-v25.json'));
const all=data.parashot.flatMap(p=>p.caminos.map(c=>({parasha:p.parasha,...c})));
const normalized=s=>s.normalize('NFC').toLocaleLowerCase('es').replace(/[^\p{L}\p{N}]/gu,'');
const questions=new Set(),titles=new Set();
assert.equal(data.parashot.length,20);
assert.equal(all.length,140);
assert(data.revision_preguntas.includes('2026-11-20'));
for(const p of data.parashot)assert.equal(p.caminos.length,7,p.parasha);
for(const c of all){
 const id=c.parasha+'/'+c.dia;
 assert(c.reflexion.length>18&&c.reflexion.length<=110,id+': longitud de pregunta');
 assert.equal((c.reflexion.match(/¿/gu)||[]).length,1,id+': inicio de pregunta');
 assert.equal((c.reflexion.match(/\?/gu)||[]).length,1,id+': cierre de pregunta');
 assert(c.titulo.length>4&&c.titulo.length<=65,id+': título legible');
 assert(!/^[A-ZÁÉÍÓÚÜÑ ]+$/u.test(c.titulo),id+': falta título en español');
 assert(c.pasuk.hebreo&&c.pasuk.ref&&c.pasuk.es,id+': pasaje');
 assert(Object.keys(c.voces||{}).length>=4,id+': voces tradicionales');
 assert(c.paraLlevar.avoda&&c.paraLlevar.kavana&&c.paraLlevar.hitbodedut,id+': práctica');
 assert(c.paraLlevar.avoda.length<=190,id+': práctica demasiado larga');
 assert((c.paraLlevar.avoda.match(/¿/gu)||[]).length<=1,id+': práctica con cuestionario');
 assert(!/[¿?]/u.test(c.paraLlevar.hitbodedut),id+': Hitbodedut con interrogantes');
 assert(!questions.has(normalized(c.reflexion)),id+': pregunta duplicada');
 assert(!titles.has(normalized(c.titulo)),id+': título duplicado');
 questions.add(normalized(c.reflexion));
 titles.add(normalized(c.titulo));
 if(c.tituloTranslit)assert(c.tituloTranslit.length>1,id+': transliteración');
}
assert.equal(all.filter(c=>c.tituloTranslit).length,84);
assert.equal(questions.size,140);
assert.equal(titles.size,140);
const v=data.parashot.find(p=>p.parasha==='Vayetze');
assert(v);
assert.equal(v.caminos[4].pasuk.ref,'Bereshit 31:7');
assert(v.caminos[4].reflexion.includes('cambia lo acordado'));
assert.equal(v.caminos[5].pasuk.ref,'Bereshit 31:38');
assert(v.caminos[5].reflexion.includes('reconoce tu esfuerzo'));
const runtime=read('prelaunch-local.js');
const html=read('index.html');
assert(runtime.includes('content/caminos-ramak-v25.json?v=claridad-140-caminos-20261120-1'));
assert(html.includes('src="prelaunch-local.js?v=claridad-140-caminos-20261120-1"'));
assert(runtime.includes('HEBREO TRANSLITERADO'));
assert(runtime.includes('const glossTerm=c.tituloTranslit||c.titulo;'));
assert(!/src="deep-review-v\d+\.js/.test(html));
new vm.Script(runtime,{filename:'prelaunch-local.js'});
console.log('PASS · 140 Caminos, títulos claros y hebreo conservado en Raíz.');
